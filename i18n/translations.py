def get_text(ui_mode: str, key: str, default: str = "") -> str:
    """Safe getter: tr = get_text('AR/FR', 'title')"""
    return TRANSLATIONS.get(ui_mode, {}).get(key, default or key)

def get_translations(ui_mode: str) -> dict:
    """Returns full dict for a mode, fallback to AR/FR"""
    return TRANSLATIONS.get(ui_mode, TRANSLATIONS["AR/FR"])
